const DICTS = { nl: NL, en: EN };

export function lang() {
  const s = storage.load();
  if (s.lang && DICTS[s.lang]) return s.lang;
  const nav = (navigator.language || 'en').toLowerCase();
  return nav.startsWith('nl') ? 'nl' : 'en';
}

export function setLang(l) {
  storage.update(s => { s.lang = l; });
  document.documentElement.lang = l;
}

export function t(k, params = {}) {
  let s = DICTS[lang()][k] ?? NL[k] ?? k;
  for (const [p, v] of Object.entries(params)) s = s.split('{' + p + '}').join(v);
  return s;
}

// Vul alle elementen met data-i18n="sleutel".
export function applyStatic(root = document) {
  document.documentElement.lang = lang();
  root.querySelectorAll('[data-i18n]').forEach(el => { el.innerHTML = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-label]').forEach(el => el.setAttribute('aria-label', t(el.dataset.i18nLabel)));
}
